class Supplier {

  final String id;

  final String marketplaceProfileId;

  final String companyName;

  final String contactPerson;

  final String email;

  final String phone;

  final String address;

  final bool verified;

  final double rating;

  const Supplier({

    required this.id,

    required this.marketplaceProfileId,

    required this.companyName,

    required this.contactPerson,

    required this.email,

    required this.phone,

    required this.address,

    required this.verified,

    required this.rating,
  });
}